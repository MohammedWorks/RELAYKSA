const isAr = () => document.documentElement.lang === "ar";
const t = (k) => MSG[k][isAr() ? 1 : 0];

const textNodes = document.querySelectorAll("[data-i18n]");
const phNodes = document.querySelectorAll("[data-i18n-ph]");
// Remember each element's own English text so switching back is exact.
const EN = new WeakMap();
const EN_PH = new WeakMap();
textNodes.forEach((el) => EN.set(el, el.textContent));
phNodes.forEach((el) => EN_PH.set(el, el.placeholder));

function fillCities() {
  const i = isAr() ? 1 : 0;
  document.querySelectorAll("select[data-cities]").forEach((sel) => {
    const v = sel.value;
    sel.innerHTML =
      `<option value="">${t("choose_city")}</option>` +
      Object.entries(CITY_NAMES).map(([k, n]) => `<option value="${k}">${n[i]}</option>`).join("");
    sel.value = v;
  });
  document.querySelectorAll("[data-city-chips]").forEach((box) => {
    const checked = new Set([...box.querySelectorAll("input:checked")].map((x) => x.value));
    box.innerHTML = Object.entries(CITY_NAMES)
      .map(([k, n]) => `<label class="chip"><input type="checkbox" name="cities" value="${k}"${checked.has(k) ? " checked" : ""}><span>${n[i]}</span></label>`)
      .join("");
  });
}

function setLang(lang) {
  const ar = lang === "ar";
  textNodes.forEach((el) => {
    const v = ar ? AR[el.dataset.i18n] : EN.get(el);
    if (v) el.textContent = v;
  });
  phNodes.forEach((el) => {
    const v = ar ? AR[el.dataset.i18nPh] : EN_PH.get(el);
    if (v) el.placeholder = v;
  });
  document.documentElement.lang = lang;
  document.documentElement.dir = ar ? "rtl" : "ltr";
  const btn = document.getElementById("lang");
  if (btn) btn.textContent = ar ? "English" : "العربية";
  fillCities();
  try { localStorage.setItem("relay-lang", lang); } catch {}
}

